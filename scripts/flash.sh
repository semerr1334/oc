#!/usr/bin/env bash
# ============================================================
# Безопасная запись образа OC OS на USB-флешку.
#
#   sudo scripts/flash.sh [образ.img] [/dev/sdX]
#
# Скрипт НЕ ДАСТ стереть вашу основную систему:
#   * пишет только на ЦЕЛЫЕ диски вида /dev/sdX (не разделы);
#   * отказывается, если на диске есть примонтированные разделы;
#   * отказывается, если диск системный (на нём /, /boot, /home...);
#   * отказывается на не-USB накопителях и дисках больше 64 GiB;
#   * требует ДВА подтверждения перед записью.
# Обойти проверки (только если Вы понимаете, что делаете): FORCE=1.
# ============================================================
set -euo pipefail

IMG="${1:-build/oc.img}"
DEV="${2:-}"
MAX_SIZE=$((64 * 1024 * 1024 * 1024))    # 64 GiB

die()  { echo "ОШИБКА: $*" >&2; exit 1; }
info() { echo "── $*"; }

[ -f "$IMG" ] || die "нет образа '$IMG' (сначала выполните: make)"
[ "$(id -u)" = 0 ] || die "нужны права root: sudo $0 $IMG ${DEV:-/dev/sdX}"
[ -n "$DEV" ] || die "укажите устройство флешки:
  sudo $0 $IMG /dev/sdX
Список дисков: lsblk -o NAME,SIZE,MODEL,TRAN,MOUNTPOINT
Ищите свою флешку по TRAN=usb и размеру."

# ---- 1. только целый диск, не раздел --------------------------------
case "$DEV" in
    /dev/sd[a-z]|/dev/vd[a-z]|/dev/hd[a-z]) ;;
    /dev/nvme*|/dev/mmcblk*)
        die "'$DEV' — NVMe/eMMC. Образ OC пишется только на простые USB-диски вида /dev/sdX." ;;
    /dev/sd[a-z][0-9]*|/dev/vd[a-z][0-9]*|/dev/hd[a-z][0-9]*|/dev/*p[0-9]*)
        die "'$DEV' — похоже на РАЗДЕЛ, а не на диск. Укажите диск целиком (например /dev/sdb)." ;;
    *)
        die "подозрительное имя устройства '$DEV' — отказ." ;;
esac
[ -b "$DEV" ] || die "'$DEV' не существует или не блочное устройство"

BASE=$(basename "$DEV")

# ---- 2. никаких примонтированных файловых систем ---------------------
MNT=$(lsblk -nro MOUNTPOINT "$DEV" | grep -v '^$' || true)
[ -z "$MNT" ] || die "на $DEV есть примонтированные разделы:
$MNT
Размонтируйте их (umount ...) и повторите — ваша ОС остаётся целой."

# ---- 3. диск не системный -------------------------------------------
for src in $(findmnt -nro SOURCE | grep '^/dev/' | sort -u); do
    pk=$(lsblk -no PKNAME "$src" 2>/dev/null | head -1 || true)
    [ -n "$pk" ] || pk=$(basename "$src")
    if [ "$pk" = "$BASE" ]; then
        die "$src (смонтированный системный раздел!) лежит на $DEV.
Это Ваш основной диск — на него я НЕ буду писать."
    fi
done
info "системные разделы не на этом диске — ок"

# ---- 4. флешка, а не винчестер ---------------------------------------
TRAN=$(lsblk -no TRAN "$DEV" | head -1 || true)
if [ "$TRAN" != "usb" ] && [ "${FORCE:-0}" != "1" ]; then
    die "'$DEV' не USB-флешка (TRAN=${TRAN:-?}). Если точно уверены: FORCE=1 $0 ..."
fi
info "интерфейс: ${TRAN:-неизвестен}"

# ---- 5. размер флешки, а не диска -----------------------------------
SZ=$(lsblk -no SIZE --bytes "$DEV" | head -1 || echo 0)
if [ "$SZ" -gt "$MAX_SIZE" ] && [ "${FORCE:-0}" != "1" ]; then
    die "$DEV имеет размер $SZ байт — это похоже на винчестер/SSD, а не флешку.
Если точно уверены: FORCE=1 $0 ..."
fi

# ---- 6. двойное подтверждение ----------------------------------------
echo
echo "=== Запись образа:  $IMG ($(stat -c%s "$IMG") байт)"
echo "=== Устройство:     $DEV ($(lsblk -no MODEL,SIZE "$DEV" | head -1 | xargs))"
echo "!!! ВСЕ ДАННЫЕ НА $DEV БУДУТ УНИЧТОЖЕНЫ !!!"
echo
printf 'Введите имя устройства ещё раз (%s): ' "$DEV"
read -r ANS
[ "$ANS" = "$DEV" ] || die "имена не совпали — отмена."
printf 'Введите YES для записи: '
read -r YES
[ "$YES" = "YES" ] || die "отмена."

dd if="$IMG" of="$DEV" bs=4M conv=fsync status=progress
sync
echo
echo "Готово! Теперь можно загружаться с $DEV (Boot Menu / BIOS)."
