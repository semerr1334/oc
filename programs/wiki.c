/* вход по нулевому смещению файла — секция .text.entry (см. scripts/ocp.ld) */
void _entry(void);
__attribute__((section(".text.entry"))) void _entry(void) { ocp_start(); }

void ocp_start(void)
{
    int cur = 0;
    for (;;) {
        writes(pages[cur]);
        writes("\nСсылки: [1] Главная [2] Windows [3] Интернет "
               "[4] Клавиши [5] О .ocp | [q] Выход\nВыбор: ");
        long k = 0;
        while (!(k = getkey()))
            sleep_ms(20);
        if (k == 'q' || k == 'Q' || k == 27)
            break;
        if (k >= '1' && k <= '5')
            cur = (int)(k - '1');
    }
    writes("\nДо встречи в OC!\n");
    exit(0);
}
